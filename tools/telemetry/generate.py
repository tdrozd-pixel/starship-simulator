def _type_text(f):
    typ = f["type"]
    rec = _record_name(typ)
    base = f"{rec} record" if rec is not None else typ
    if "count" in f:
        return f"{base}[{f['count']}]" if rec is None else f"{rec}[{f['count']}]"
    return base


def _notes(f, d):
    parts = []
    if f.get("unit"):
        parts.append(f"[{f['unit']}]")
    if f.get("description"):
        parts.append(f["description"])
    text = " ".join(parts)
    extra = []
    if "enum" in f:
        extra.append(", ".join(f"{e['value']} {e['name']}" for e in d["enums"][f["enum"]]))
    if "bits" in f:
        extra.append(", ".join(f"bit {i} {b['description']} (`{b['name']}`)" for i, b in enumerate(f["bits"])))
    if f.get("boolean"):
        extra.append("0 or 1")
    if "limits" in f:
        extra.append("limits " + json.dumps(f["limits"]))
    if extra:
        text = (text + ": " if text else "") + "; ".join(extra)
    return text


def _md_table(fields, d, L):
    L.append("| Offset | Type | Field | Notes |")
    L.append("|---:|---|---|---|")
    for f in fields:
        if f["type"] == "pad":
            L.append(f"| {f['offset']} | u8[{f['count']}] | pad | 0 |")
        else:
            L.append(f"| {f['offset']} | {_type_text(f)} | {f['name']} | {_notes(f, d)} |")


def generate_md(d, lay):
    with open(TEMPLATE_PATH, "r", encoding="utf-8", newline="") as fh:
        tmpl = fh.read().replace("\r\n", "\n")
    table = ["| APID | Name | Rate | User data length |", "|---|---|---|---|"]
    for p in lay["packets"]:
        table.append(f"| 0x{p['apid']:X} ({p['apid']}) | {p['title']} | {rate_text(p)} | {p['userDataLength']} |")
    sections = []
    for p in lay["packets"]:
        sections.append(f"### 0x{p['apid']:X} {p['title']}")
        sections.append("")
        sections.append(p["description"])
        sections.append("")
        _md_table(p["fields"], d, sections)
        sections.append("")
        used = []
        for f in p["fields"]:
            rec = _record_name(f["type"])
            if rec is not None and rec not in used:
                used.append(rec)
        for rname in used:
            r = lay["records"][rname]
            sections.append(f"Record `{rname}` ({r['size']} bytes), repeated {p_count(p, rname)} times, "
                            f"record i at the field offset plus {r['size']} i. {r['description']}")
            sections.append("")
            _md_table(r["fields"], d, sections)
            sections.append("")
    consts = ["| Constant | Value | Unit | Meaning | Source |", "|---|---:|---|---|---|"]
    for c in d["constants"]:
        consts.append(f"| `{c['name']}` | {c['value']} | {c.get('unit', '')} | {c['description']} | {c['source']} |")
    out = tmpl
    out = out.replace("{{VERSION}}", str(d["version"]))
    out = out.replace("{{APID_TABLE}}", "\n".join(table))
    out = out.replace("{{PACKET_SECTIONS}}", "\n".join(sections) + "\n")
    out = out.replace("{{CONSTANTS}}", "\n".join(consts))
    return f"<!-- {BANNER} -->\n\n" + out


def p_count(packet, rname):
    for f in packet["fields"]:
        if _record_name(f["type"]) == rname:
            return f.get("count", 1)
    return 1


