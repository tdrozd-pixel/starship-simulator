def _cpp_member_type(field):
    typ = field["type"]
    rec = _record_name(typ)
    if rec is not None:
        base = pascal(rec)
    elif field.get("boolean"):
        base = "bool"
    else:
        base = SCALARS[typ][1]
    if "count" in field:
        return f"std::array<{base}, {field['count']}>"
    return base


def _cpp_put(typ, expr, off_expr):
    fn = {"u8": "putU8", "u16": "putU16", "u32": "putU32", "f32": "putF32", "f64": "putF64"}[typ]
    return f"detail::{fn}(out + {off_expr}, {expr});"


def _cpp_encode_fields(fields, indent, out_lines):
    pad = " " * indent
    for f in fields:
        typ = f["type"]
        if typ == "pad":
            out_lines.append(f"{pad}// pad: {f['count']} zero byte(s) at offset {f['offset']}")
            continue
        name = f["name"]
        rec = _record_name(typ)
        count = f.get("count")
        if "bits" in f:
            parts = [f"(p.{b['name']} ? {1 << i}U : 0U)" for i, b in enumerate(f["bits"])]
            expr = "static_cast<uint8_t>(" + " | ".join(parts) + ")"
            out_lines.append(f"{pad}detail::putU8(out + {f['offset']}, {expr});")
            continue
        if rec is not None:
            call = f"encode(p.{name}[i], out + {f['offset']} + {f['elemSize']} * i);"
            out_lines.append(f"{pad}for (std::size_t i = 0; i < {count}; ++i) {{")
            out_lines.append(f"{pad}    {call}")
            out_lines.append(f"{pad}}}")
            continue
        value = f"p.{name}"
        if f.get("boolean"):
            conv = lambda v: f"static_cast<uint8_t>({v} ? 1U : 0U)"
        else:
            conv = lambda v: v
        if count is None:
            out_lines.append(f"{pad}" + _cpp_put(typ, conv(value), str(f["offset"])))
        else:
            out_lines.append(f"{pad}for (std::size_t i = 0; i < {count}; ++i) {{")
            out_lines.append(f"{pad}    " + _cpp_put(typ, conv(f"{value}[i]"), f"{f['offset']} + {f['elemSize']} * i"))
            out_lines.append(f"{pad}}}")


def _cpp_struct(struct_name, fields, out_lines):
    out_lines.append(f"struct {struct_name} {{")
    for f in fields:
        if f["type"] == "pad":
            continue
        desc = f.get("description", "")
        unit = f" [{f['unit']}]" if f.get("unit") else ""
        comment = f"//{unit} {desc}".rstrip() if (unit or desc) else ""
        if "bits" in f:
            for b in f["bits"]:
                out_lines.append(f"    bool {b['name']}{{}};  // flags bit {f['bits'].index(b)}: {b['description']}")
            continue
        line = f"    {_cpp_member_type(f)} {f['name']}{{}};"
        out_lines.append(f"{line}  {comment}" if comment else line)
    out_lines.append("};")


def generate_cpp(d, lay):
    L = []
    a = L.append
    a(f"// {BANNER}")
    a("#pragma once")
    a("")
    a("// GNC telemetry packet layouts, version %s. Big-endian user data; the CCSDS headers are" % d["version"])
    a("// written by fsw/Ccsds.hpp. Standard library only.")
    a("")
    a("#include <array>")
    a("#include <cstddef>")
    a("#include <cstdint>")
    a("#include <cstring>")
    a("")
    a("namespace fsw::telemetry {")
    a("")
    a("namespace detail {")
    a("")
    a("inline void putU8(uint8_t* p, uint8_t v) { p[0] = v; }")
    a("")
    a("inline void putU16(uint8_t* p, uint16_t v) {")
    a("    p[0] = static_cast<uint8_t>(v >> 8);")
    a("    p[1] = static_cast<uint8_t>(v);")
    a("}")
    a("")
    a("inline void putU32(uint8_t* p, uint32_t v) {")
    a("    for (int i = 0; i < 4; ++i) {")
    a("        p[i] = static_cast<uint8_t>(v >> (24 - 8 * i));")
    a("    }")
    a("}")
    a("")
    a("inline void putU64(uint8_t* p, uint64_t v) {")
    a("    for (int i = 0; i < 8; ++i) {")
    a("        p[i] = static_cast<uint8_t>(v >> (56 - 8 * i));")
    a("    }")
    a("}")
    a("")
    a("inline void putF32(uint8_t* p, float v) {")
    a("    uint32_t bits = 0;")
    a("    std::memcpy(&bits, &v, sizeof bits);")
    a("    putU32(p, bits);")
    a("}")
    a("")
    a("inline void putF64(uint8_t* p, double v) {")
    a("    uint64_t bits = 0;")
    a("    std::memcpy(&bits, &v, sizeof bits);")
    a("    putU64(p, bits);")
    a("}")
    a("")
    a("}  // namespace detail")
    a("")
    for rname, rec in lay["records"].items():
        sname = pascal(rname)
        a(f"// Record {rname}, {rec['size']} bytes: {rec['description']}")
        a(f"constexpr std::size_t k{sname}Size = {rec['size']};  // [bytes]")
        _cpp_struct(sname, rec["fields"], L)
        a("")
        a(f"// Writes the {rec['size']}-byte record at `out`; pad bytes are zeroed.")
        a(f"inline void encode(const {sname}& p, uint8_t* out) {{")
        a(f"    std::memset(out, 0, k{sname}Size);")
        _cpp_encode_fields(rec["fields"], 4, L)
        a("}")
        a("")
    for packet in lay["packets"]:
        sname = pascal(packet["name"])
        a(f"// 0x{packet['apid']:X} {packet['title']}: {packet['description']}")
        a(f"constexpr uint16_t k{sname}Apid = {hex_apid(packet['apid'])};")
        a(f"constexpr std::size_t k{sname}UserDataLength = {packet['userDataLength']};  // [bytes]")
        rate = packet["rate"]
        if rate["kind"] == "cycles":
            a(f"constexpr uint32_t k{sname}PeriodCycles = {rate['period']};  // [flight computer cycles at {CYCLE_RATE_HZ} Hz] {rate_text(packet)}")
        else:
            a(f"constexpr bool k{sname}OnNewFix = true;  // sent on the first cycle that sees a new receiver solution")
        _cpp_struct(sname, packet["fields"], L)
        a("")
        a(f"// Writes the {packet['userDataLength']} bytes of user data at `out`; pad bytes are zeroed.")
        a(f"inline void encode(const {sname}& p, uint8_t* out) {{")
        a(f"    std::memset(out, 0, k{sname}UserDataLength);")
        _cpp_encode_fields(packet["fields"], 4, L)
        a("}")
        a("")
    a("}  // namespace fsw::telemetry")
    return "\n".join(L) + "\n"


