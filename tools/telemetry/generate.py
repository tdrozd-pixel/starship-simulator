"""Telemetry dictionary code generator.

Reads telemetry/dictionary.json and writes, deterministically:
  flight_sw/include/fsw/TelemetryPackets.hpp   packet structs and big-endian encoders (C++)
  web/js/gnc/gncPackets.generated.js           packet metadata and decoders (ES module)
  docs/telemetry/gnc_packets.md                the human-readable dictionary

Usage: python -I tools/telemetry/generate.py [--check]
  --check  generate in memory, compare with the files on disk, exit 1 if any differ.

Python standard library only. Generated files are committed; the C++ build does not need Python.
"""

import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DICTIONARY_PATH = os.path.join(ROOT, "telemetry", "dictionary.json")
TEMPLATE_PATH = os.path.join(ROOT, "tools", "telemetry", "gnc_packets.md.tmpl")
OUTPUTS = {
    "cpp": os.path.join(ROOT, "flight_sw", "include", "fsw", "TelemetryPackets.hpp"),
    "js": os.path.join(ROOT, "web", "js", "gnc", "gncPackets.generated.js"),
    "md": os.path.join(ROOT, "docs", "telemetry", "gnc_packets.md"),
}
BANNER = "GENERATED by tools/telemetry/generate.py from telemetry/dictionary.json. Do not edit."

MAX_USER_DATA = 244  # [bytes] 256 max packet minus the 12 header bytes
CYCLE_RATE_HZ = 100  # [Hz] flight computer cycle rate

# type -> (size [bytes], C++ type, DataView getter, struct format char)
SCALARS = {
    "u8": (1, "uint8_t", "getUint8", "B"),
    "u16": (2, "uint16_t", "getUint16", "H"),
    "u32": (4, "uint32_t", "getUint32", "I"),
    "f32": (4, "float", "getFloat32", "f"),
    "f64": (8, "double", "getFloat64", "d"),
}
FIELD_NAME = re.compile(r"^[a-z][A-Za-z0-9]*$")
SNAKE_NAME = re.compile(r"^[a-z][a-z0-9_]*$")


class DictionaryError(Exception):
    """The dictionary is invalid."""


# ---------------------------------------------------------------------------
# Loading, validation, layout
# ---------------------------------------------------------------------------

def load_dictionary(path=DICTIONARY_PATH):
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def _record_name(type_name):
    return type_name[len("record:"):] if type_name.startswith("record:") else None


def _check_fields(where, fields, records, enums, allow_records):
    seen = set()
    for field in fields:
        name = field.get("name")
        typ = field.get("type")
        if not isinstance(name, str) or not name:
            raise DictionaryError(f"{where}: a field has no name")
        label = f"{where}.{name}"
        if typ is None:
            raise DictionaryError(f"{label}: missing type")
        rec = _record_name(typ)
        if typ == "pad":
            if name != "pad":
                raise DictionaryError(f"{label}: pad fields must be named 'pad'")
            if not isinstance(field.get("count"), int) or field["count"] < 1:
                raise DictionaryError(f"{label}: pad needs a positive integer count (bytes)")
        else:
            if name == "pad":
                raise DictionaryError(f"{label}: the name 'pad' is reserved for pad fields")
            if not FIELD_NAME.match(name):
                raise DictionaryError(f"{label}: field names are camelCase")
            if name in seen:
                raise DictionaryError(f"{label}: duplicate field name")
            seen.add(name)
            if rec is not None:
                if not allow_records:
                    raise DictionaryError(f"{label}: records may not contain records")
                if rec not in records:
                    raise DictionaryError(f"{label}: unknown record '{rec}'")
            elif typ not in SCALARS:
                raise DictionaryError(f"{label}: unknown type '{typ}'")
        if "count" in field and (not isinstance(field["count"], int) or field["count"] < 1):
            raise DictionaryError(f"{label}: count must be a positive integer")
        if "enum" in field:
            if field["enum"] not in enums:
                raise DictionaryError(f"{label}: unknown enum '{field['enum']}'")
            if typ not in ("u8", "u16", "u32"):
                raise DictionaryError(f"{label}: enum needs an unsigned integer type")
        if "bits" in field:
            if typ != "u8" or "count" in field:
                raise DictionaryError(f"{label}: bits need a scalar u8")
            bits = field["bits"]
            if not 1 <= len(bits) <= 8:
                raise DictionaryError(f"{label}: 1 to 8 bits")
            for bit in bits:
                if not FIELD_NAME.match(bit.get("name", "")):
                    raise DictionaryError(f"{label}: bit names are camelCase")
                if bit["name"] in seen:
                    raise DictionaryError(f"{label}: bit name '{bit['name']}' clashes with a field")
                seen.add(bit["name"])
        if field.get("boolean") and (typ != "u8" or "count" in field):
            raise DictionaryError(f"{label}: boolean needs a scalar u8")
        if "limits" in field:
            for level in field["limits"]:
                if level not in ("yellow", "red"):
                    raise DictionaryError(f"{label}: limits levels are yellow and red")
                bounds = field["limits"][level]
                if not (isinstance(bounds, list) and len(bounds) == 2):
                    raise DictionaryError(f"{label}: limits.{level} is [lo, hi]")


def validate(d):
    """Raise DictionaryError with a clear message if the dictionary is invalid."""
    for key in ("version", "enums", "constants", "records", "packets"):
        if key not in d:
            raise DictionaryError(f"dictionary: missing top-level key '{key}'")
    enums = d["enums"]
    for name, entries in enums.items():
        values = [e["value"] for e in entries]
        if len(set(values)) != len(values):
            raise DictionaryError(f"enum {name}: duplicate values")
    records = d["records"]
    for rname, record in records.items():
        if not SNAKE_NAME.match(rname):
            raise DictionaryError(f"record {rname}: names are snake_case")
        _check_fields(f"record {rname}", record["fields"], records, enums, allow_records=False)
    apids = {}
    names = set()
    for packet in d["packets"]:
        name = packet.get("name")
        if not isinstance(name, str) or not SNAKE_NAME.match(name):
            raise DictionaryError(f"packet {name!r}: names are snake_case")
        if name in names:
            raise DictionaryError(f"packet {name}: duplicate name")
        names.add(name)
        apid = packet.get("apid")
        if not isinstance(apid, int) or not 0 <= apid <= 0x7FF:
            raise DictionaryError(f"packet {name}: apid must be an integer in 0..2047")
        if apid in apids:
            raise DictionaryError(f"packet {name}: duplicate apid 0x{apid:X} (also {apids[apid]})")
        apids[apid] = name
        rate = packet.get("rate", {})
        if rate.get("kind") == "cycles":
            period = rate.get("period")
            if not isinstance(period, int) or period < 1 or CYCLE_RATE_HZ % period != 0:
                raise DictionaryError(f"packet {name}: rate period must divide {CYCLE_RATE_HZ} cycles")
        elif rate.get("kind") != "onNewGnssFix":
            raise DictionaryError(f"packet {name}: unknown rate kind {rate.get('kind')!r}")
        _check_fields(f"packet {name}", packet["fields"], records, enums, allow_records=True)
    # Lengths last, so structural errors are reported first.
    layout(d)


def _field_layout(field, records_layout, offset):
    typ = field["type"]
    count = field.get("count")
    n = count if count is not None else 1
    rec = _record_name(typ)
    if typ == "pad":
        elem = 1
    elif rec is not None:
        elem = records_layout[rec]["size"]
    else:
        elem = SCALARS[typ][0]
    entry = dict(field)
    entry["offset"] = offset
    entry["elemSize"] = elem
    entry["size"] = elem * n
    return entry


def layout(d):
    """Compute offsets and sizes. Returns {'records': {name: {...}}, 'packets': [...]}."""
    records = {}
    for rname, record in d["records"].items():
        offset = 0
        fields = []
        for field in record["fields"]:
            entry = _field_layout(field, records, offset)
            offset += entry["size"]
            fields.append(entry)
        records[rname] = {"name": rname, "title": record.get("title", rname),
                          "description": record.get("description", ""), "size": offset, "fields": fields}
    packets = []
    for packet in d["packets"]:
        offset = 0
        fields = []
        for field in packet["fields"]:
            entry = _field_layout(field, records, offset)
            offset += entry["size"]
            fields.append(entry)
        if offset > MAX_USER_DATA:
            raise DictionaryError(
                f"packet {packet['name']}: user data is {offset} bytes, the maximum is {MAX_USER_DATA}")
        p = dict(packet)
        p["fields"] = fields
        p["userDataLength"] = offset
        packets.append(p)
    return {"records": records, "packets": packets}


