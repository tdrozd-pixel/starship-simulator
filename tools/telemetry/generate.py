def pascal(snake):
    return "".join(w[:1].upper() + w[1:] for w in snake.split("_"))


def hex_apid(apid):
    return f"0x{apid:X}"


def rate_hz(packet):
    rate = packet["rate"]
    if rate["kind"] == "cycles":
        return CYCLE_RATE_HZ // rate["period"]
    return rate.get("nominalHz")


def rate_text(packet):
    rate = packet["rate"]
    if rate["kind"] == "cycles":
        return f"{rate_hz(packet)} Hz"
    hz = rate.get("nominalHz")
    return f"each new fix ({hz} Hz)" if hz else "each new fix"


def js_str(s):
    return json.dumps(s, ensure_ascii=True)


