def _js_read(typ, off):
    getter = SCALARS[typ][2]
    return f"dv.{getter}({off})" if typ == "u8" else f"dv.{getter}({off}, false)"


def _js_off(base, off):
    if base is None:
        return str(off)
    return base if off == 0 else f"{base} + {off}"


def _js_field_exprs(fields, base):
    """Yield (key, expression) pairs in order; the flags prelude is handled by the caller."""
    items = []
    for f in fields:
        typ = f["type"]
        if typ == "pad":
            continue
        name = f["name"]
        rec = _record_name(typ)
        count = f.get("count")
        if "bits" in f:
            items.append((name, name))
            for i, b in enumerate(f["bits"]):
                items.append((b["name"], f"({name} & {1 << i}) !== 0"))
            continue

        def one(k):
            off = _js_off(base, f["offset"] + k * f["elemSize"])
            if rec is not None:
                return f"decode{pascal(rec)}(dv, {off})"
            e = _js_read(typ, off)
            return f"{e} !== 0" if f.get("boolean") else e

        if count is None:
            items.append((name, one(0)))
        else:
            items.append((name, "[" + ", ".join(one(k) for k in range(count)) + "]"))
    return items


def _js_body(fields, base, indent, L):
    pad = " " * indent
    for f in fields:
        if "bits" in f:
            L.append(f"{pad}const {f['name']} = {_js_read('u8', _js_off(base, f['offset']))};")
    L.append(f"{pad}return {{")
    for key, expr in _js_field_exprs(fields, base):
        L.append(f"{pad}  {key}: {expr}," if key != expr else f"{pad}  {key},")
    L.append(f"{pad}}};")


def _meta_field(f):
    m = {"name": f["name"], "type": f["type"]}
    if "count" in f:
        m["count"] = f["count"]
    m["offset"] = f["offset"]
    m["size"] = f["size"]
    for key in ("unit", "description", "enum", "bits", "boolean", "limits"):
        if key in f:
            m[key] = f[key]
    return m


def generate_js(d, lay):
    meta_packets = {}
    for p in lay["packets"]:
        entry = {"name": p["name"], "title": p["title"], "apid": p["apid"],
                 "userDataLength": p["userDataLength"], "description": p["description"],
                 "rate": p["rate"], "fields": [_meta_field(f) for f in p["fields"]]}
        meta_packets[p["name"]] = entry
    meta_records = {}
    for rname, r in lay["records"].items():
        meta_records[rname] = {"name": rname, "title": r["title"], "size": r["size"],
                               "description": r["description"], "fields": [_meta_field(f) for f in r["fields"]]}
    L = []
    a = L.append
    a(f"// {BANNER}")
    a("// GNC packet metadata and user-data decoders (big-endian), version %s." % d["version"])
    a("// Decoders take a DataView over the packet user data and return plain objects.")
    a("")
    a(f"export const DICTIONARY_VERSION = {d['version']};")
    a("")
    a("export const ENUMS = " + json.dumps(d["enums"], indent=2) + ";")
    a("")
    a("// Vehicle constants the console needs (not downlinked).")
    a("export const CONSTANTS = " + json.dumps({c["name"]: c["value"] for c in d["constants"]}, indent=2) + ";")
    a("")
    a("export const RECORDS = " + json.dumps(meta_records, indent=2) + ";")
    a("")
    a("export const PACKETS = " + json.dumps(meta_packets, indent=2) + ";")
    a("")
    for rname, r in lay["records"].items():
        a(f"// Record {rname} ({r['size']} bytes) at byte offset `o` of the user data.")
        a(f"function decode{pascal(rname)}(dv, o) {{")
        _js_body(r["fields"], "o", 2, L)
        a("}")
        a("")
    for p in lay["packets"]:
        a(f"// 0x{p['apid']:X} {p['title']} ({p['userDataLength']} bytes).")
        a(f"export function decode{pascal(p['name'])}(dv) {{")
        _js_body(p["fields"], None, 2, L)
        a("}")
        a("")
    a("// Decoders and user data lengths by APID.")
    a("export const DECODERS = {")
    for p in lay["packets"]:
        a(f"  {hex_apid(p['apid'])}: decode{pascal(p['name'])},")
    a("};")
    a("export const USER_LENGTH = {")
    for p in lay["packets"]:
        a(f"  {hex_apid(p['apid'])}: {p['userDataLength']},")
    a("};")
    return "\n".join(L) + "\n"


