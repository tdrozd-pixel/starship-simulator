def generate_all(d=None):
    """Return {path: text} for every generated file."""
    d = d if d is not None else load_dictionary()
    validate(d)
    lay = layout(d)
    return {
        OUTPUTS["cpp"]: generate_cpp(d, lay),
        OUTPUTS["js"]: generate_js(d, lay),
        OUTPUTS["md"]: generate_md(d, lay),
    }


def main(argv):
    check = "--check" in argv
    try:
        files = generate_all()
    except DictionaryError as e:
        print(f"error: {e}", file=sys.stderr)
        return 2
    if check:
        stale = []
        for path, text in files.items():
            try:
                with open(path, "rb") as fh:
                    on_disk = fh.read()
            except OSError:
                on_disk = None
            if on_disk != text.encode("utf-8"):
                stale.append(os.path.relpath(path, ROOT))
        if stale:
            print("generated files differ from the dictionary (run tools/telemetry/generate.py):", file=sys.stderr)
            for s in stale:
                print(f"  {s}", file=sys.stderr)
            return 1
        print("telemetry generated files are up to date")
        return 0
    for path, text in files.items():
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
        print(f"wrote {os.path.relpath(path, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
